"""Export firmware u8g2 fonts as a C header so host renderers rasterize real glyphs."""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pixel_font import PixelFont  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
FONTS = {'primary': 'u8g2_font_helvB08_tr', 'secondary': 'u8g2_font_haxrcorp4089_tr'}


def export(target):
    source = ROOT / 'firmware/flipper/lib/u8g2/u8g2_fonts.c'
    lines = ['// Generated by scripts/host_fonts.py from u8g2_fonts.c. Host tests only.',
             '#pragma once', '#include <stdint.h>',
             'typedef struct { int8_t w, h, dx, dy, advance; uint16_t bits; } HostGlyph;',
             'typedef struct { const HostGlyph* glyphs; const uint8_t* bits; } HostFont;']
    for key, name in FONTS.items():
        font = PixelFont(source, name)
        glyphs, bits, cursor = [], [], 0
        for code in range(32, 127):
            ch = chr(code)
            w, h, dx, dy, advance, pixels = font.glyphs.get(ch, (0, 0, 0, 0, 0, []))
            on = set(pixels)
            packed = [(px, py) in on for py in range(h) for px in range(w)]
            glyphs.append(f'{{{w},{h},{dx},{dy},{advance},{cursor}}}')
            bits.extend(packed)
            cursor += len(packed)
        data = bytes(sum(bits[i + b] << b for b in range(8) if i + b < len(bits))
                     for i in range(0, len(bits), 8))
        lines.append(f'static const HostGlyph host_{key}_glyphs[95] = {{' + ','.join(glyphs) + '};')
        lines.append(f'static const uint8_t host_{key}_bits[] = {{' + ','.join(map(str, data)) + '};')
    lines.append('static const HostFont host_fonts[2] = {{host_primary_glyphs, host_primary_bits},'
                 ' {host_secondary_glyphs, host_secondary_bits}};')
    Path(target).write_text('\n'.join(lines) + '\n', encoding='ascii')


if __name__ == '__main__':
    export(sys.argv[1])
