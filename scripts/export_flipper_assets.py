from pathlib import Path
import json
from PIL import Image, ImageDraw
from pixel_font import PixelFont

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'assets/whale-girl'
target = ROOT / 'firmware/flipper/applications/services/deepflipper'
m = json.loads((source/'manifest.json').read_text(encoding='utf-8'))
raw = (source/'whale_frames.bin').read_bytes()
lines = ['// Generated by scripts/export_flipper_assets.py', '#pragma once',
         '#include <stdint.h>', f'#define DF_FRAME_COUNT {m["unique_frame_count"]}',
         'static const uint8_t df_fallback[512] = {']
for i in range(0,512,16):
    lines.append('    '+','.join(f'0x{x:02x}' for x in raw[i:i+16])+',')
lines.append('};')
for a in m['animations']:
    lines.append(f'static const uint8_t df_seq_{a["id"]}[] = {{'+','.join(map(str,a['frames']))+'};')
lines.append('static const uint8_t* const df_sequences[] = {'+
             ','.join('df_seq_'+a['id'] for a in m['animations'])+'};')
lines.append('static const uint8_t df_sequence_sizes[] = {'+
             ','.join(str(len(a['frames'])) for a in m['animations'])+'};')
lines.append('static const uint8_t df_mouth[3][4] = {')
for name in ('closed','small','open'):
    im=Image.open(source/f'mouth_{name}.png')
    rows=[sum((im.getpixel((25+x,33+y))==0)<<x for x in range(5)) for y in range(4)]
    lines.append('    {'+','.join(map(str,rows))+'},')
lines.append('};')
(target/'whale_data.h').write_text('\n'.join(lines)+'\n',encoding='ascii')
destination=target/'resources/deepflipper'
destination.mkdir(parents=True,exist_ok=True)
(destination/'whale_frames.bin').write_bytes(raw)
print('Exported bounded animation tables, fallback and SD frame data.')

# Passport is an SD application with nine mood/level icon slots. Keep the slot
# names and statistics intact, replacing their art with a native-pixel bust crop.
portraits = ROOT / 'firmware/flipper/assets/icons/Passport'
for mood, state, frame in (('happy', 'happy', 3), ('okay', 'idle', 0), ('bad', 'angry', 3)):
    sprite = Image.open(source / 'frames' / state / f'{frame:02d}.png').convert('1')
    # Continue the hair, collar and shoulders instead of adding a floating emblem.
    portrait = sprite.crop((4, 0, 50, 49))
    ImageDraw.Draw(portrait).rectangle((22, 47, 31, 48), fill=1)
    for level in (1, 2, 3):
        portrait.save(portraits / f'passport_{mood}{level}_46x49.png')
    portrait.save(source / f'passport_{mood}.png')
print('Exported whale-girl Passport bust portraits without a separate whale emblem.')

# Preview the existing Passport layout with sample statistics and the new avatar.
card = Image.new('1', (128, 64), 1)
card.paste(Image.open(portraits / 'passport_left_6x46.png').convert('1'), (0, 0))
card.paste(Image.open(portraits / 'passport_bottom_128x18.png').convert('1'), (0, 46))
draw = ImageDraw.Draw(card)
draw.line((6, 0, 125, 0), fill=0)
draw.line((127, 2, 127, 47), fill=0)
draw.point((126, 1), fill=0)
card.paste(Image.open(portraits / 'passport_happy1_46x49.png').convert('1'), (9, 5))
font = PixelFont(ROOT / 'firmware/flipper/lib/u8g2/u8g2_fonts.c', 'u8g2_font_haxrcorp4089_tr')
for baseline, text in ((12, 'DeepSeek'), (26, 'Mood: Happy'), (40, 'Level: 1')):
    font.draw(card, 58, baseline, text)
    draw.line((58, baseline + 4, 123, baseline + 4), fill=0)
draw.rectangle((103, 47, 123, 52), fill=1)
draw.line((123, 47, 123, 52), fill=0)
preview = Image.new('RGB', card.size)
preview.putdata([(233, 168, 63) if pixel else (37, 30, 19) for pixel in card.getdata()])
preview.resize((768, 384), Image.Resampling.NEAREST).save(source / 'passport_preview.png')
